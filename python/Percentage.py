# Total and percentage of five subjects
m1 = float(input("Subject 1 marks: "))
m2 = float(input("Subject 2 marks: "))
m3 = float(input("Subject 3 marks: "))
m4 = float(input("Subject 4 marks: "))
m5 = float(input("Subject 5 marks: "))

